#!/usr/bin/env python3
"""Generate test/host/fixtures/noise_ik_vectors.h with the independent Python `noiseprotocol` package.

The host test (test_secure.c) replays the same handshake with components/clu_secure/clu_noise.c and
compares every message and the split transport keys byte for byte.

    python3 -I test/host/fixtures/gen_noise_vectors.py > test/host/fixtures/noise_ik_vectors.h
"""
from noise.connection import Keypair, NoiseConnection

NAME = b"Noise_IK_25519_AESGCM_SHA256"
PROLOGUE = b"opengr8on-sec-v1"
I_S = bytes(range(0x01, 0x21))
R_S = bytes(range(0x21, 0x41))
I_E = bytes(range(0x41, 0x61))
R_E = bytes(range(0x61, 0x81))
P1 = b"1:12345:c"
P2 = b"1:67890:c"
T1 = b"req:10.0.0.1:0000abcd:checkAlive()"


def conn(initiator: bool) -> NoiseConnection:
    c = NoiseConnection.from_name(NAME)
    c.set_prologue(PROLOGUE)
    if initiator:
        c.set_as_initiator()
        c.set_keypair_from_private_bytes(Keypair.STATIC, I_S)
        c.set_keypair_from_private_bytes(Keypair.EPHEMERAL, I_E)
        r = NoiseConnection.from_name(NAME)
        r.set_keypair_from_private_bytes(Keypair.STATIC, R_S)
        c.set_keypair_from_public_bytes(Keypair.REMOTE_STATIC, r.noise_protocol.keypairs["s"].public_bytes)
    else:
        c.set_as_responder()
        c.set_keypair_from_private_bytes(Keypair.STATIC, R_S)
        c.set_keypair_from_private_bytes(Keypair.EPHEMERAL, R_E)
    c.start_handshake()
    return c


def c_array(name: str, data: bytes) -> str:
    body = ",".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};"


def main() -> None:
    i, r = conn(True), conn(False)
    m1 = i.write_message(P1)
    assert r.read_message(m1) == P1
    m2 = r.write_message(P2)
    assert i.read_message(m2) == P2
    assert i.handshake_finished and r.handshake_finished
    # Transport key of the initiator's sending direction (Noise Split() k1): first transport message.
    t1 = i.encrypt(T1)
    k1 = i.noise_protocol.cipher_state_encrypt.k
    k2 = i.noise_protocol.cipher_state_decrypt.k
    rs_pub = r.noise_protocol.keypairs["s"].public_bytes
    print("// Generated by gen_noise_vectors.py (Python noiseprotocol). Do not edit.")
    print("#pragma once")
    print("#include <stdint.h>")
    for name, data in [
        ("V_PROLOGUE", PROLOGUE), ("V_I_S", I_S), ("V_R_S", R_S), ("V_I_E", I_E), ("V_R_E", R_E),
        ("V_R_S_PUB", rs_pub), ("V_P1", P1), ("V_P2", P2), ("V_MSG1", m1), ("V_MSG2", m2),
        ("V_K1", k1), ("V_K2", k2), ("V_T1_PLAIN", T1), ("V_T1", t1),
    ]:
        print(c_array(name, data))


if __name__ == "__main__":
    main()
